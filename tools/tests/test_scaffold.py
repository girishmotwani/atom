"""Behaviour tests for spike scaffolding (B35-B43).

These are written before scaffold.py exists. The first run must fail with an
import error -- that is the RED step, and it is recorded in tdd-log.md.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

import pytest

from atom.runner import CommandOutcome, CommandResult
from atom.scaffold import (
    ScaffoldError,
    SlugError,
    scaffold_spike,
)


class FakeGoModInit:
    """A runner that reproduces `go mod init`'s side effect, not just its exit code.

    A fake that only returned an exit code would let a broken scaffold pass:
    the code under test could skip running the command entirely and the test
    would still be green. Writing a real go.mod is what makes the assertion
    about B36 meaningful.
    """

    def __init__(self, *, should_succeed: bool = True) -> None:
        self.should_succeed = should_succeed
        self.calls: list[tuple[tuple[str, ...], Path]] = []

    def run(
        self,
        command: Sequence[str],
        working_directory: Path,
        timeout_seconds: float = 300.0,
        stdin_text: str | None = None,
    ) -> CommandResult:
        command_tuple = tuple(command)
        self.calls.append((command_tuple, working_directory))

        if not self.should_succeed:
            return CommandResult(
                command_tuple,
                working_directory,
                CommandOutcome.COMPLETED,
                1,
                "",
                "go: cannot determine module path",
                0.1,
            )

        # Mirror the real tool: write go.mod pinning the full patch version.
        module_path = command_tuple[-1]
        (working_directory / "go.mod").write_text(
            f"module {module_path}\n\ngo 1.23.4\n", encoding="utf-8"
        )
        return CommandResult(command_tuple, working_directory, CommandOutcome.COMPLETED, 0, "", "", 0.1)


@pytest.fixture
def poc_root(tmp_path: Path) -> Path:
    root = tmp_path / "poc"
    root.mkdir()
    return root


def test_scaffold_creates_exactly_three_files(poc_root: Path) -> None:
    """B35: a spike is go.mod, main.go and README.md -- nothing else."""

    result = scaffold_spike(poc_root, "json-streaming", "Does streaming beat buffering?", FakeGoModInit())

    created_names = sorted(path.name for path in result.directory.iterdir())
    assert created_names == ["README.md", "go.mod", "main.go"]


def test_scaffold_shells_out_to_go_mod_init(poc_root: Path) -> None:
    """B36: go.mod is generated by the toolchain, never written from a template."""

    runner = FakeGoModInit()
    scaffold_spike(poc_root, "json-streaming", "A question", runner)

    commands = [call[0] for call in runner.calls]
    assert ("go", "mod", "init", "spike/json-streaming") in commands


def test_scaffold_go_mod_pins_full_patch_version(poc_root: Path) -> None:
    """B36: the generated go.mod carries whatever the toolchain wrote.

    The POC showed `go mod init` writes `go 1.23.4`, not `go 1.23`. A template
    would have hard-coded the wrong thing, so this asserts we kept the tool's
    output rather than substituting our own.
    """

    result = scaffold_spike(poc_root, "json-streaming", "A question", FakeGoModInit())

    go_mod_text = (result.directory / "go.mod").read_text(encoding="utf-8")
    assert "go 1.23.4" in go_mod_text


def test_scaffold_module_path_is_namespaced_under_spike(poc_root: Path) -> None:
    """B37: module path is spike/<slug>, deliberately not a real domain."""

    result = scaffold_spike(poc_root, "json-streaming", "A question", FakeGoModInit())

    assert result.module_path == "spike/json-streaming"


def test_scaffold_rolls_back_completely_when_go_mod_init_fails(poc_root: Path) -> None:
    """B38: a half-created spike is worse than none -- it breaks the parent build."""

    with pytest.raises(ScaffoldError):
        scaffold_spike(poc_root, "doomed", "A question", FakeGoModInit(should_succeed=False))

    assert not (poc_root / "doomed").exists(), "a spike dir without go.mod breaks `go build ./...`"


def test_scaffold_rollback_leaves_sibling_spikes_untouched(poc_root: Path) -> None:
    """B38: rollback removes only the failed spike, never a neighbour."""

    scaffold_spike(poc_root, "keeper", "A question", FakeGoModInit())

    with pytest.raises(ScaffoldError):
        scaffold_spike(poc_root, "doomed", "A question", FakeGoModInit(should_succeed=False))

    assert (poc_root / "keeper" / "go.mod").exists()


def test_scaffold_main_go_is_package_main_with_a_main_function(poc_root: Path) -> None:
    """B39: a freshly scaffolded spike always runs."""

    result = scaffold_spike(poc_root, "json-streaming", "Does streaming beat buffering?", FakeGoModInit())

    main_go = (result.directory / "main.go").read_text(encoding="utf-8")
    assert main_go.startswith("package main")
    assert "func main()" in main_go


def test_scaffold_main_go_prints_the_question(poc_root: Path) -> None:
    """B39: the question travels with the code, so a spike is never anonymous."""

    question = "Does streaming beat buffering?"
    result = scaffold_spike(poc_root, "json-streaming", question, FakeGoModInit())

    assert question in (result.directory / "main.go").read_text(encoding="utf-8")


def test_scaffold_main_go_documents_the_exit_code_convention(poc_root: Path) -> None:
    """B40: the developer must not have to look up what exit 2 means."""

    result = scaffold_spike(poc_root, "json-streaming", "A question", FakeGoModInit())

    main_go = (result.directory / "main.go").read_text(encoding="utf-8")
    for expected in ("0", "1", "2", "Confirmed", "Refuted", "Inconclusive"):
        assert expected in main_go, f"exit-code convention missing {expected!r}"


def test_scaffold_readme_has_the_report_sections(poc_root: Path) -> None:
    """B41: the README is the first draft of the POC report."""

