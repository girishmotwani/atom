@pytest.mark.parametrize(
    "bad_slug",
    [
        "Json-Streaming",   # uppercase
        "json_streaming",   # underscore
        "json streaming",   # space
        "-leading",         # leading hyphen
        "trailing-",        # trailing hyphen
        "double--hyphen",   # empty segment
        "",                 # empty
        "../escape",        # path traversal
    ],
)
def test_scaffold_rejects_unusable_slugs(poc_root: Path, bad_slug: str) -> None:
    """B42: the slug becomes both a directory name and a module path."""

    with pytest.raises(SlugError):
        scaffold_spike(poc_root, bad_slug, "A question", FakeGoModInit())


@pytest.mark.parametrize("good_slug", ["json", "json-streaming", "http2-vs-http3", "a1"])
def test_scaffold_accepts_valid_slugs(poc_root: Path, good_slug: str) -> None:
    """B42: the rule must not be so strict it rejects reasonable names."""

    result = scaffold_spike(poc_root, good_slug, "A question", FakeGoModInit())

    assert result.slug == good_slug


def test_scaffold_slug_error_explains_the_rule(poc_root: Path) -> None:
    """B42: an error that does not say what is allowed just costs a round trip."""

    with pytest.raises(SlugError) as error:
        scaffold_spike(poc_root, "Bad Slug", "A question", FakeGoModInit())

    assert "lowercase" in str(error.value).lower()


def test_scaffold_refuses_to_overwrite_an_existing_spike(poc_root: Path) -> None:
    """B43: a spike may hold observations that cannot be reproduced."""

    scaffold_spike(poc_root, "json-streaming", "Original question", FakeGoModInit())

    with pytest.raises(FileExistsError):
        scaffold_spike(poc_root, "json-streaming", "Different question", FakeGoModInit())


def test_scaffold_does_not_modify_an_existing_spike_when_refusing(poc_root: Path) -> None:
    """B43: refusing must be a true no-op, not a partial write then a raise."""

    first = scaffold_spike(poc_root, "json-streaming", "Original question", FakeGoModInit())
    before = (first.directory / "main.go").read_text(encoding="utf-8")

    with pytest.raises(FileExistsError):
        scaffold_spike(poc_root, "json-streaming", "Different question", FakeGoModInit())

    assert (first.directory / "main.go").read_text(encoding="utf-8") == before


def test_scaffold_creates_poc_root_when_missing(tmp_path: Path) -> None:
    """A repo scaffolding its first spike has no poc/ directory yet."""

    result = scaffold_spike(tmp_path / "poc", "first-spike", "A question", FakeGoModInit())

    assert result.directory.exists()


def test_scaffold_reports_every_file_it_created(poc_root: Path) -> None:
    """B35: the CLI tells the developer where to go next, so it needs the list."""

    result = scaffold_spike(poc_root, "json-streaming", "A question", FakeGoModInit())

    assert sorted(path.name for path in result.files_created) == ["README.md", "go.mod", "main.go"]

